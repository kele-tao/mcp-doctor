"""Coverage summary generator: docs/COVERAGE.md is a real measurement, not a claim.

Run from the repository root:

    python benchmarks/coverage.py

It runs the test suite under coverage.py and writes a per-module table to
docs/COVERAGE.md. The README quotes the total from that file, and
tests/test_docs.py asserts the two agree, so the number cannot drift silently.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "COVERAGE.md"


def run(argv: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        argv, cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace"
    )


def main() -> int:
    probe = run([sys.executable, "-m", "coverage", "--version"])
    if probe.returncode != 0:
        print('coverage.py is required: pip install -e ".[dev]"', file=sys.stderr)
        return 2
    run([sys.executable, "-m", "coverage", "run", "-m", "pytest", "-q"])
    report = run([sys.executable, "-m", "coverage", "report", "--include=src/*"])
    data = run([sys.executable, "-m", "coverage", "json", "-o", "-", "--include=src/*"])
    if report.returncode != 0:
        print(report.stdout + report.stderr, file=sys.stderr)
        return 1
    import json

    totals = json.loads(data.stdout)["totals"]
    lines = [
        "# Test coverage",
        "",
        "Generated by python benchmarks/coverage.py, which runs the full test suite",
        "under coverage.py and records the result. The README quotes the total below.",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        "| Statements | " + str(totals["num_statements"]) + " |",
        "| Covered | " + str(totals["covered_lines"]) + " |",
        "| Missed | " + str(totals["missing_lines"]) + " |",
        "| Line coverage | " + str(round(totals["percent_covered"], 1)) + "% |",
        "",
        "## Per module",
        "",
        "| Module | Statements | Missed | Cover |",
        "| --- | ---: | ---: | ---: |",
    ]
    for name, info in json.loads(data.stdout)["files"].items():
        short = name.replace(chr(92), "/").split("src/")[-1]
        lines.append(
            "| "
            + short
            + " | "
            + str(info["summary"]["num_statements"])
            + " | "
            + str(info["summary"]["missing_lines"])
            + " | "
            + str(round(info["summary"]["percent_covered"], 1))
            + "% |"
        )
    lines += [
        "",
        "Coverage is measured over src/ only: the examples, the benchmark harness and",
        "the tests themselves are exercise material, not shipped code.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote " + str(OUT.relative_to(ROOT)))
    print("total line coverage: " + str(round(totals["percent_covered"], 1)) + "%")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
